import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
// @ts-expect-error Native Node test execution requires the source extension.
import { MICHELLE_MAKAREM_USER_ID, skipsAutoPrework } from "./no-auto-prework-clients.ts";

test("Michelle's sessions never get automatic pre-work; other clients still do", () => {
  assert.equal(skipsAutoPrework({ clientUserId: MICHELLE_MAKAREM_USER_ID }), true);
  assert.equal(skipsAutoPrework({ clientUserId: ` ${MICHELLE_MAKAREM_USER_ID.toUpperCase()} ` }), true);
  assert.equal(skipsAutoPrework({ clientUserId: "1c8c622f-a75f-471c-9b5e-34e136905118" }), false);
  assert.equal(skipsAutoPrework({ clientUserId: null }), false);
  assert.equal(skipsAutoPrework({}), false);
});

test("booking-time autogen returns before any pre-work assignment for those clients", () => {
  const source = readFileSync(new URL("./autogenerated-sat-prework.ts", import.meta.url), "utf8");
  const guard = source.indexOf("if (skipsAutoPrework(session))");
  assert.ok(guard > 0, "guard missing");
  const guardBlock = source.slice(guard, source.indexOf("return { skipped: true, reason: \"client-no-auto-prework\" }", guard));
  assert.match(guardBlock, /ensureHardSatInSession\(session\)/, "in-session set should still generate");
  assert.doesNotMatch(guardBlock, /ensureHardSatPrework|assignSessionPreworkFromBank/);
  assert.ok(guard < source.indexOf("ensureHardSatPrework(session"), "guard must run before hard pre-work");
  assert.ok(guard < source.indexOf("assignSessionPreworkFromBank({"), "guard must run before bank pre-work");
});

test("hard session sets skip only the pre-work half for those clients", () => {
  const source = readFileSync(new URL("./sat-hard-sets.ts", import.meta.url), "utf8");
  const start = source.indexOf("export async function ensureHardSatSessionSets(");
  const body = source.slice(start, source.indexOf("\n}\n", start));
  assert.match(body, /skipsAutoPrework\(session\)\s*\?\s*null\s*:\s*await ensureHardSatPrework\(session, actorUserId\)/);
  assert.match(body, /const inSession = await ensureHardSatInSession\(session\);/);
});
