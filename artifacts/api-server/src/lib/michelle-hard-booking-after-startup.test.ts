import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";
import { ADMIN_CALENDAR_ACCOUNT_EMAIL } from "./admin-calendar-fallback.ts";
import { michelleHardBookingContract } from "./michelle-hard-booking-contract.ts";
import {
  MICHELLE_FUTURE_HARD_SAT_REFRESH_INTERVAL_MS,
  startMichelleFutureHardSatSetRefresh,
} from "./michelle-hard-booking.ts";
import { MICHELLE_MAKAREM_USER_ID } from "./no-auto-prework-clients.ts";
import { MICHELLE_MAKAREM_MEET_URL } from "./session-meeting-url.ts";

const platformSource = readFileSync(new URL("../routes/platform.ts", import.meta.url), "utf8");
const indexSource = readFileSync(new URL("../index.ts", import.meta.url), "utf8");
const bookingSource = readFileSync(new URL("./michelle-hard-booking.ts", import.meta.url), "utf8");
const hardSetsSource = readFileSync(new URL("./sat-hard-sets.ts", import.meta.url), "utf8");

test("a Michelle booking made after startup still gets a complete hard SAT hour", () => {
  const ran: string[] = [];
  let intervalMsUsed = 0;
  const refresh = startMichelleFutureHardSatSetRefresh({
    intervalMs: 60_000,
    runOnStart: true,
    run: async () => {
      ran.push("startup-or-interval");
    },
    setIntervalFn: ((fn, ms) => {
      intervalMsUsed = Number(ms);
      ran.push("interval-scheduled");
      return 1 as unknown as ReturnType<typeof setInterval>;
    }) as typeof setInterval,
    clearIntervalFn: ((handle) => {
      ran.push(`cleared:${String(handle)}`);
    }) as typeof clearInterval,
  });
  assert.ok(ran.includes("startup-or-interval"), "startup refresh still runs once");
  assert.ok(ran.includes("interval-scheduled"), "a periodic safety net is scheduled after startup");
  assert.equal(intervalMsUsed, 60_000);
  refresh.stop();

  // Booking-time provision is wired on every confirmed SAT booking path, not
  // only the one-shot startup job.
  const tutorCreate = platformSource.slice(
    platformSource.indexOf("session.created"),
    platformSource.indexOf('"/tutor/quizzes"'),
  );
  assert.match(tutorCreate, /provisionSatSessionOnBooking\(created!, user\.id\)/);

  const studentConfirm = platformSource.slice(
    platformSource.indexOf("const confirmBookedSession = async"),
    platformSource.indexOf("if (calendarPlan.mode === \"manual\")"),
  );
  assert.match(studentConfirm, /provisionSatSessionOnBooking\(session, req\.appUser!\.id\)/);
  assert.doesNotMatch(
    studentConfirm,
    /await ensureAutogeneratedSatPrework\(session\.id/,
    "student booking must not skip the reserve by calling only pre-work",
  );

  const adminCreateAt = platformSource.indexOf('"/admin/sessions"');
  const adminCreate = platformSource.slice(
    adminCreateAt,
    platformSource.indexOf('"/admin/sessions/:sessionId"', adminCreateAt),
  );
  assert.match(adminCreate, /provisionSatSessionOnBooking\(created, req\.appUser!\.id\)/);

  assert.match(indexSource, /startMichelleFutureHardSatSetRefresh\(\{ runOnStart: false \}\)/);
  assert.match(bookingSource, /MICHELLE_FUTURE_HARD_SAT_REFRESH_INTERVAL_MS = 15 \* 60 \* 1000/);
  assert.equal(MICHELLE_FUTURE_HARD_SAT_REFRESH_INTERVAL_MS, 15 * 60 * 1000);
  assert.match(
    hardSetsSource,
    /MICHELLE_NOV16_SOPHIA_LAMAS_SESSION_ID/,
  );
  assert.match(hardSetsSource, /blocked-by-attempts/);
  assert.match(hardSetsSource, /isOfficialHardTailItem/);

  const sophia = michelleHardBookingContract({
    dateTime: new Date("2026-11-24T14:00:00.000Z"),
    timezone: "Asia/Dubai",
    tutorName: "Sophia Lamas",
    tutorEmail: "sophia.e.lamas@gmail.com",
    sessionTitle: "Michelle’s SAT Session with Sophia",
    clientUserId: MICHELLE_MAKAREM_USER_ID,
  });
  assert.deepEqual(sophia.sections, ["rw"]);
  assert.equal(sophia.prework.questions, 40);
  assert.equal(sophia.prework.minutes, 50);
  assert.equal(sophia.prework.status, "published");
  assert.equal(
    sophia.prework.title,
    "Nov 24 Pre-work SAT English (Hard) — Michelle x Sophia L",
  );
  assert.equal(sophia.inSession.questions, 15);
  assert.equal(sophia.inSession.minutes, 30);
  assert.equal(
    sophia.inSession.title,
    "Nov 24 In-session SAT English (Hard) — Michelle x Sophia L",
  );
  assert.equal(sophia.reserve.questions, 5);
  assert.equal(sophia.reserve.minutes, 30);
  assert.equal(sophia.reserve.status, "draft");
  assert.equal(
    sophia.reserve.title,
    "Nov 24 In-session SAT English Reserve (Hard) — Michelle x Sophia L",
  );
  assert.equal(sophia.officialHardTailFirst, true);
  assert.equal(sophia.meetUrl, MICHELLE_MAKAREM_MEET_URL);
  assert.equal(sophia.meetUrl, "https://meet.google.com/ase-tqtz-ywj");
  assert.equal(sophia.calendarOrganizer, ADMIN_CALENDAR_ACCOUNT_EMAIL);
  assert.equal(sophia.invitesOrganizedByAdmin, true);
  assert.equal(sophia.attachNextSatPrepDeck, true);

  const xavier = michelleHardBookingContract({
    dateTime: new Date("2026-11-29T17:00:00.000Z"),
    timezone: "America/New_York",
    tutorName: "Xavier Morales",
    tutorEmail: "xavier.rmz6@gmail.com",
    sessionTitle: "Michelle’s SAT Session with Xavier",
  });
  assert.deepEqual(xavier.sections, ["math"]);
  assert.equal(
    xavier.prework.title,
    "Nov 29 Pre-work SAT Math (Hard) — Michelle x Xavier",
  );
  assert.equal(
    xavier.inSession.title,
    "Nov 29 In-session SAT Math (Hard) — Michelle x Xavier",
  );
  assert.equal(
    xavier.reserve.title,
    "Nov 29 In-session SAT Math Reserve (Hard) — Michelle x Xavier",
  );
  assert.equal(xavier.meetUrl, "https://meet.google.com/ase-tqtz-ywj");
  assert.equal(xavier.attachNextSatPrepDeck, false);
  assert.equal(xavier.invitesOrganizedByAdmin, true);

  const eunice = michelleHardBookingContract({
    dateTime: new Date("2026-12-01T14:00:00.000Z"),
    timezone: "America/New_York",
    tutorName: "Eunice",
    tutorEmail: "eunice_chon@berkeley.edu",
    sessionTitle: "Michelle’s SAT Session with Eunice",
  });
  assert.deepEqual(eunice.sections, ["rw", "math"]);
  assert.equal(eunice.subjectLabel, "SAT (Hard)");
  assert.equal(eunice.prework.title, "Dec 1 Pre-work SAT (Hard) — Michelle x Eunice");
  assert.equal(eunice.meetUrl, "https://meet.google.com/ase-tqtz-ywj");
  assert.equal(eunice.attachNextSatPrepDeck, false);
});

test("booking-time provision uses official hard-tail items first and never touches attempted or Nov 16 sets", () => {
  assert.match(bookingSource, /isMichelleFutureHardSatSession\(session\)/);
  assert.match(bookingSource, /ensureHardSatSessionSets\(session, actorUserId\)/);
  assert.match(bookingSource, /ensureHardChallengeReserve\(session\)/);
  assert.match(bookingSource, /ensureMichelleSophiaLamasSatPrepSlidesSafe\(session\.id\)/);
  assert.match(bookingSource, /ensureMichelleXavierHardMathBank\(\)/);
  assert.match(
    hardSetsSource,
    /if \(session\.id === MICHELLE_NOV16_SOPHIA_LAMAS_SESSION_ID\) return false/,
  );
  assert.match(hardSetsSource, /blocked-by-attempts/);
  const select = readFileSync(new URL("./sat-routine-form.ts", import.meta.url), "utf8");
  assert.match(select, /isOfficialHardTailItem/);
  const reserve = readFileSync(new URL("./sat-hard-reserve.ts", import.meta.url), "utf8");
  assert.match(reserve, /isOfficialHardTailItem/);
});
