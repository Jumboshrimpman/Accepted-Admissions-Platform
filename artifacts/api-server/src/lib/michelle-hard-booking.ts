/** Cheap safety-net interval. Booking-time provision is the primary path. */
export const MICHELLE_FUTURE_HARD_SAT_REFRESH_INTERVAL_MS = 15 * 60 * 1000;

type SessionRow = typeof sessionsTable.$inferSelect;

async function loadSession(
  sessionOrId: SessionRow | { id: string },
): Promise<SessionRow | null> {
  if ("courseId" in sessionOrId && "subject" in sessionOrId && "dateTime" in sessionOrId) {
    return sessionOrId as SessionRow;
  }
  const [session] = await db
    .select()
    .from(sessionsTable)
    .where(eq(sessionsTable.id, sessionOrId.id))
    .limit(1);
  return session ?? null;
}

/**
 * Provision SAT homework at booking time: hard pre-work, in-session, and
 * reserve for Michelle's later sessions; otherwise the standard auto pre-work
 * path. Also attaches the next SAT Prep I–IV deck on Michelle × Sophia Lamas
 * bookings. Never throws past the caller if the bank is empty — callers still
 * wrap this in try/catch so a booking is not rolled back.
 */
export async function provisionSatSessionOnBooking(
  sessionOrId: SessionRow | { id: string },
  actorUserId?: string | null,
): Promise<{ action: "michelle-hard" | "standard-sat" | "skipped"; reason?: string }> {
  const session = await loadSession(sessionOrId);
  if (!session) return { action: "skipped", reason: "session-not-found" };
  if ((session.status ?? "").trim() === "archived") return { action: "skipped", reason: "archived" };
  if ((session.bookingStatus ?? "").trim() === "cancelled") {
    return { action: "skipped", reason: "cancelled" };
  }

  if (isMichelleFutureHardSatSession(session)) {
    await ensureMichelleXavierHardMathBank();
    await ensureHardSatSessionSets(session, actorUserId);
    if (!skipsAutoPrework(session)) {
      try {
        await ensureHardChallengeReserve(session);
      } catch {
        // Reserve is best-effort; the periodic refresh retries.
      }
    }
    await ensureMichelleSophiaLamasSatPrepSlidesSafe(session.id);
    return { action: "michelle-hard" };
  }

  if (
    isEnglishSessionSubject(session.subject) ||
    normalizedSessionSubject(session.subject) !== "SAT"
  ) {
    await ensureMichelleSophiaLamasSatPrepSlidesSafe(session.id);
    return { action: "skipped", reason: "not-sat" };
  }

  await ensureAutogeneratedSatPrework(session.id, actorUserId);
  try {
    await ensureHardChallengeReserve(session);
  } catch {
    // Standard hard students still get a reserve when the pool allows it.
  }
  await ensureMichelleSophiaLamasSatPrepSlidesSafe(session.id);
  return { action: "standard-sat" };
}

/**
 * Startup plus a cheap periodic refresh of Michelle's later unattempted SAT
 * sets. Attempted work, Nov 15, and Nov 16 are left in place by the helper.
 */
export function startMichelleFutureHardSatSetRefresh(options?: {
  intervalMs?: number;
  setIntervalFn?: typeof setInterval;
  clearIntervalFn?: typeof clearInterval;
  run?: () => Promise<unknown>;
  runOnStart?: boolean;
}): { stop: () => void } {
  const intervalMs = options?.intervalMs ?? MICHELLE_FUTURE_HARD_SAT_REFRESH_INTERVAL_MS;
  const schedule = options?.setIntervalFn ?? setInterval;
  const clear = options?.clearIntervalFn ?? clearInterval;
  const run =
    options?.run ??
    (() =>
      ensureMichelleFutureHardSatSets()
        .then((result) => {
          logger.info(
            { considered: result.considered, shortfalls: result.shortfalls },
            "Michelle future hard SAT sets check",
          );
          return result;
        })
        .catch((err) => {
          logger.warn({ err }, "Michelle future hard SAT sets check skipped");
        }));
  if (options?.runOnStart !== false) void run();
  const handle = schedule(() => {
    void run();
  }, intervalMs);
  return {
    stop: () => clear(handle as ReturnType<typeof setInterval>),
  };
}
